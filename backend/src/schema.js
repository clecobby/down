// Table definitions for both databases. SQLite sets itself up on start; DSQL is set up once with
// `npm run migrate` (DSQL runs one DDL statement per transaction, so they're kept separate).

const TABLES = ({ id, ts, real }) => [
  `CREATE TABLE IF NOT EXISTS users (
    id            ${id},
    cognito_sub   TEXT UNIQUE,              -- Cognito user id; null for seeded demo profiles
    email         TEXT UNIQUE NOT NULL,
    username      TEXT UNIQUE,
    password_hash TEXT NOT NULL DEFAULT '', -- unused since Cognito; kept for old databases
    name          TEXT NOT NULL,
    birthdate     TEXT NOT NULL,
    gender        TEXT NOT NULL,            -- man | woman | nonbinary
    interested_in TEXT NOT NULL,            -- comma list of genders
    bio           TEXT DEFAULT '',
    photo         TEXT DEFAULT '',          -- main photo (= first of photos)
    photos        TEXT DEFAULT '',          -- JSON array, up to 6
    tags          TEXT DEFAULT '',          -- comma list of vibe tags
    turn_ons      TEXT DEFAULT '',          -- comma list of turn-on ids
    height_cm     INTEGER,
    city          TEXT DEFAULT '',
    available_now INTEGER DEFAULT 0,
    lat           ${real},
    lng           ${real},
    county        TEXT DEFAULT '',
    region        TEXT DEFAULT '',
    country       TEXT DEFAULT '',
    banned        INTEGER DEFAULT 0,
    banned_reason TEXT DEFAULT '',
    last_active   ${ts} NOT NULL,
    created_at    ${ts} NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS swipes (
    from_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    to_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dir        TEXT NOT NULL,               -- like | pass
    created_at ${ts} NOT NULL,
    PRIMARY KEY (from_id, to_id)
  )`,
  `CREATE TABLE IF NOT EXISTS matches (
    id         ${id},
    a          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    b          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at ${ts} NOT NULL,
    UNIQUE (a, b)
  )`,
  `CREATE TABLE IF NOT EXISTS messages (
    id         ${id},
    match_id   BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    sender_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body       TEXT NOT NULL,
    created_at ${ts} NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS meetups (
    id          ${id},
    match_id    BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    proposer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    place       TEXT NOT NULL,
    time        TEXT NOT NULL,
    status      TEXT NOT NULL DEFAULT 'pending', -- pending | accepted | declined
    created_at  ${ts} NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS blocks (
    blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (blocker_id, blocked_id)
  )`,
  `CREATE TABLE IF NOT EXISTS reports (
    id          ${id},
    reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reported_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason      TEXT NOT NULL,
    status      TEXT DEFAULT 'open',        -- open | dismissed | actioned
    resolved_at ${ts},
    created_at  ${ts} NOT NULL
  )`,
  // "I'm down" signals between two matched people. Private until both have sent one; they expire.
  `CREATE TABLE IF NOT EXISTS down_signals (
    match_id   BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at ${ts} NOT NULL,
    expires_at ${ts} NOT NULL,
    PRIMARY KEY (match_id, user_id)
  )`,
  // Runtime settings the admin dashboard can change (e.g. demo mode).
  `CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
  )`,
  // Who did what in the admin dashboard.
  `CREATE TABLE IF NOT EXISTS admin_log (
    id         ${id},
    admin      TEXT NOT NULL,              -- admin's email
    action     TEXT NOT NULL,
    target     TEXT,
    detail     TEXT,
    created_at ${ts} NOT NULL
  )`,
];

const INDEXES = [
  ['users_county', 'users (country, region, county)'],
  ['swipes_to', 'swipes (to_id)'],
  ['messages_match', 'messages (match_id, id)'],
  ['meetups_match', 'meetups (match_id)'],
  ['reports_reported', 'reports (reported_id)'],
];

// Aurora DSQL: identity columns for ids, BIGINT millisecond timestamps, async index builds.
export const dsqlSchema = [
  ...TABLES({ id: 'BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY', ts: 'BIGINT', real: 'DOUBLE PRECISION' }),
  ...INDEXES.map(([name, on]) => `CREATE INDEX ASYNC IF NOT EXISTS ${name} ON ${on}`),
];

export function sqliteSchema(db) {
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');
  for (const t of TABLES({ id: 'INTEGER PRIMARY KEY AUTOINCREMENT', ts: 'INTEGER', real: 'REAL' })) db.exec(t);

  // Databases created by earlier versions: add the columns they're missing.
  const has = (table) => new Set(db.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name));
  const users = has('users');
  for (const [name, type] of [
    ['turn_ons', "TEXT DEFAULT ''"], ['banned', 'INTEGER DEFAULT 0'], ['banned_reason', "TEXT DEFAULT ''"], ['photos', "TEXT DEFAULT ''"],
    ['tags', "TEXT DEFAULT ''"], ['height_cm', 'INTEGER'], ['cognito_sub', 'TEXT'], ['username', 'TEXT'], ['lat', 'REAL'], ['lng', 'REAL'],
    ['county', "TEXT DEFAULT ''"], ['region', "TEXT DEFAULT ''"], ['country', "TEXT DEFAULT ''"],
  ]) {
    if (!users.has(name)) db.exec(`ALTER TABLE users ADD COLUMN ${name} ${type}`);
  }
  const reports = has('reports');
  if (!reports.has('status')) db.exec("ALTER TABLE reports ADD COLUMN status TEXT DEFAULT 'open'");
  if (!reports.has('resolved_at')) db.exec('ALTER TABLE reports ADD COLUMN resolved_at INTEGER');
  db.exec('CREATE UNIQUE INDEX IF NOT EXISTS users_username ON users(username)');
  db.exec('CREATE UNIQUE INDEX IF NOT EXISTS users_cognito_sub ON users(cognito_sub)');
  for (const [name, on] of INDEXES) db.exec(`CREATE INDEX IF NOT EXISTS ${name} ON ${on}`);
}
